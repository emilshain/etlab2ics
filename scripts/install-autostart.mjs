/*
 * Installs (or removes) the hidden autostart entry that keeps the calendar
 * bridge running at logon.
 *
 *   node scripts/install-autostart.mjs
 *   node scripts/install-autostart.mjs --remove
 *
 * Windows only: it writes a .vbs launcher into the current user's Startup
 * folder. Nothing needs administrator rights.
 */

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const project = path.resolve(here, '..');
const launcher = path.join(project, 'start-calendar.vbs');
const taskName = 'ETLab Calendar Bridge.vbs';

const startupDir = path.join(
  process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming'),
  'Microsoft',
  'Windows',
  'Start Menu',
  'Programs',
  'Startup'
);
const installed = path.join(startupDir, taskName);

if (process.platform !== 'win32') {
  console.error('This installer is Windows-only.');
  console.error('On macOS/Linux, start the bridge from your session autostart, e.g.');
  console.error(`  ${process.execPath} ${path.join(project, 'calendar-bridge.mjs')}`);
  process.exit(1);
}

if (process.argv.includes('--remove')) {
  let removed = 0;
  for (const file of [installed, launcher]) {
    if (fs.existsSync(file)) {
      fs.rmSync(file);
      console.log('removed ' + file);
      removed++;
    }
  }
  if (!removed) console.log('nothing to remove.');
  console.log('\nThe bridge may still be running. Stop it from Task Manager, or kill the');
  console.log('node process, otherwise it keeps serving until you log out.');
  process.exit(0);
}

// The launcher runs node directly (no cmd.exe redirect) and the bridge writes
// its own .bridge.log, so quoting stays simple and works from any drive.
const vbs = [
  "' ETLab calendar bridge - hidden supervisor.",
  "' Generated by scripts/install-autostart.mjs - re-run it if you move this folder.",
  "' Starts the bridge with no console window and restarts it if it exits.",
  'Set shell = CreateObject("WScript.Shell")',
  `project = "${project}"`,
  'Do',
  '  shell.CurrentDirectory = project',
  `  shell.Run """" & "${process.execPath}" & """ calendar-bridge.mjs", 0, True`,
  '  WScript.Sleep 15000',
  'Loop',
  ''
].join('\r\n');

fs.writeFileSync(launcher, vbs);
fs.mkdirSync(startupDir, { recursive: true });
fs.copyFileSync(launcher, installed);

console.log('node      : ' + process.execPath);
console.log('project   : ' + project);
console.log('launcher  : ' + launcher);
console.log('installed : ' + installed);
console.log('\nThe bridge will start at every logon from now on.');
console.log('To undo: node scripts/install-autostart.mjs --remove');
